let LANG = 'en';
function t(k) {
  const v = (I18N[LANG] && I18N[LANG][k] !== undefined) ? I18N[LANG][k] : I18N.es[k];
  return v !== undefined ? v : k;
}
function applyLang() {
  document.querySelectorAll('[data-i18n]:not(optgroup)').forEach(el => { el.innerHTML = t(el.dataset.i18n); });
  document.querySelectorAll('optgroup[data-i18n]').forEach(el => { el.label = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  document.documentElement.lang = LANG;
  document.querySelectorAll('#langSeg button, .langSegX button').forEach(b =>
    b.classList.toggle('on', b.dataset.lang === LANG));
  /* S7: el título del saludo lleva el nombre dinámico → re-renderizarlo */
  if (typeof renderHello === 'function') {
    var hs = document.getElementById('s-onb-hello');
    if (hs && hs.classList.contains('active')) renderHello();
  }
  /* S3: el arte depende del idioma → re-renderizarlo si está visible */
  if (typeof renderBack === 'function') {
    var bs = document.getElementById('s-onb-back');
    if (bs && bs.classList.contains('active')) renderBack();
  }
  /* recetas de la usuaria: el contenido dinámico se re-renderiza con el idioma actual */
  if (typeof renderUserRecipes === 'function') renderUserRecipes();
  if (typeof renderUserCats === 'function') renderUserCats();
  if (typeof renderRecipeDetail === 'function' && typeof currentRecipeId !== 'undefined' && currentRecipeId) {
    var rv = document.getElementById('s-receta-ver');
    if (rv && rv.classList.contains('active')) renderRecipeDetail(currentRecipeId);
  }
}
